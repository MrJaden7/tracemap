-- Overrides the generator's stub. Mapping: mapping_spec/cdm_source.yml v0.1.0.
-- One row per CDM build, taken from the latest completed row in etl_meta.cdm_run.

{{ config(materialized='table', schema='cdm', alias='cdm_source') }}

with latest_run as (
    select run_id, started_at, finished_at, synthea_version, vocabulary_version
    from {{ source('etl_meta', 'cdm_run') }}
    where status = 'completed'
    order by started_at desc
    limit 1
),
latest_event as (
    select max(coalesce(stop, start)::date) as source_release_date
    from {{ ref('stg_synthea__encounters') }}
)

select
    'TraceMap synthetic Synthea dataset'                                    as cdm_source_name,
    'TRACEMAP'                                                              as cdm_source_abbreviation,
    'Jaden Menezes'                                                         as cdm_holder,
    'Synthea v' || coalesce(r.synthea_version, '?') ||
      ' synthetic patient records (Massachusetts, US). Synthetic data only.' as source_description,
    'https://github.com/synthetichealth/synthea'                            as source_documentation_reference,
    'Generated by TraceMap. See docs/decisions/ for architectural decisions.' as cdm_etl_reference,
    e.source_release_date,
    coalesce(r.finished_at::date, current_date)                             as cdm_release_date,
    'v5.4'                                                                  as cdm_version,
    756265                                                                  as cdm_version_concept_id,
    coalesce(r.vocabulary_version, 'unknown')                               as vocabulary_version
from latest_run r, latest_event e
