"""Walk a CDM row back to its exact source.

A CDM row's lineage is: the source raw table, the row number inside that file, the file
SHA-256 at load time, and the run that loaded it. Two shapes exist:

1. **Direct trace** (event tables): the CDM row's surrogate id IS `_source_row` from the
   raw table. condition_occurrence_id, visit_occurrence_id, drug_exposure_id and the
   others are assigned this way, so the lookup is straightforward.

2. **Key-map trace** (person, care_site, provider, location): the CDM row's id is
   generated by an intermediate model (int_*_key_map) that records the source row it
   came from, so the trace walks through that table.

The map between CDM table and (source table, lookup shape) is declared once in this
module and verified by tests, so the trace never silently guesses.
"""

from dataclasses import dataclass
from typing import Literal

import psycopg

from tracemap.db import connect

Shape = Literal["direct", "key_map"]


@dataclass(frozen=True)
class TraceSpec:
    cdm_table: str
    cdm_id_column: str
    source_table: str
    shape: Shape
    key_map_table: str | None = None
    key_map_id_column: str | None = None


# Hand-curated: one entry per Phase 1 CDM table that has a stable surrogate id.
# observation_period, cdm_source and metadata are derived at build time so their lineage
# is the whole latest run, not one source row; `trace` reports this.
TRACES: dict[str, TraceSpec] = {
    "person": TraceSpec(
        "person",
        "person_id",
        "raw.synthea_patients",
        "key_map",
        "etl_meta.person_key_map",
        "person_id",
    ),
    "care_site": TraceSpec(
        "care_site",
        "care_site_id",
        "raw.synthea_organizations",
        "key_map",
        "etl_meta.care_site_key_map",
        "care_site_id",
    ),
    "provider": TraceSpec(
        "provider",
        "provider_id",
        "raw.synthea_providers",
        "key_map",
        "etl_meta.provider_key_map",
        "provider_id",
    ),
    "visit_occurrence": TraceSpec(
        "visit_occurrence",
        "visit_occurrence_id",
        "raw.synthea_encounters",
        "direct",
    ),
    "condition_occurrence": TraceSpec(
        "condition_occurrence",
        "condition_occurrence_id",
        "raw.synthea_conditions",
        "direct",
    ),
    "drug_exposure": TraceSpec(
        "drug_exposure",
        "drug_exposure_id",
        "raw.synthea_medications",
        "direct",
    ),
    "procedure_occurrence": TraceSpec(
        "procedure_occurrence",
        "procedure_occurrence_id",
        "raw.synthea_procedures",
        "direct",
    ),
    "measurement": TraceSpec(
        "measurement",
        "measurement_id",
        "raw.synthea_observations",
        "direct",
    ),
    "observation": TraceSpec(
        "observation",
        "observation_id",
        "raw.synthea_observations",
        "direct",
    ),
}


@dataclass(frozen=True)
class TraceResult:
    cdm_table: str
    cdm_id: int
    cdm_row: dict | None
    source_table: str
    source_row: int | None
    run_id: int | None
    file_name: str | None
    file_sha256: str | None
    file_path: str | None
    source_data: dict | None


def _row_as_dict(cursor: psycopg.Cursor, row: tuple) -> dict:
    cols = [desc.name for desc in cursor.description]
    return dict(zip(cols, row, strict=False))


def trace_row(cdm_table: str, cdm_id: int) -> TraceResult:
    """Look up one CDM row and walk it back to the source CSV."""
    spec = TRACES.get(cdm_table)
    if spec is None:
        raise ValueError(
            f"Unknown or non-traceable CDM table: {cdm_table}. Options: {', '.join(sorted(TRACES))}"
        )

    with connect() as conn, conn.cursor() as cur:
        cur.execute(
            f"SELECT * FROM cdm.{spec.cdm_table} WHERE {spec.cdm_id_column} = %s",
            (cdm_id,),
        )
        row = cur.fetchone()
        cdm_row = _row_as_dict(cur, row) if row else None
        if cdm_row is None:
            return TraceResult(
                cdm_table,
                cdm_id,
                None,
                spec.source_table,
                None,
                None,
                None,
                None,
                None,
                None,
            )

        if spec.shape == "direct":
            source_row = int(cdm_id)
        else:
            cur.execute(
                f"SELECT source_row, run_id "
                f"FROM {spec.key_map_table} WHERE {spec.key_map_id_column} = %s",
                (cdm_id,),
            )
            km_row = cur.fetchone()
            source_row = int(km_row[0]) if km_row else None

        cur.execute(
            f"SELECT * FROM {spec.source_table} WHERE _source_row = %s",
            (source_row,),
        )
        src = cur.fetchone()
        source_data = _row_as_dict(cur, src) if src else None
        run_id = int(source_data["_run_id"]) if source_data else None

        file_name = file_sha256 = file_path = None
        if run_id is not None:
            cur.execute(
                "SELECT file_name, file_sha256, file_path FROM raw.load_manifest "
                "WHERE run_id = %s AND target_table = %s",
                (run_id, spec.source_table),
            )
            m = cur.fetchone()
            if m:
                file_name, file_sha256, file_path = m

    return TraceResult(
        cdm_table=cdm_table,
        cdm_id=cdm_id,
        cdm_row=cdm_row,
        source_table=spec.source_table,
        source_row=source_row,
        run_id=run_id,
        file_name=file_name,
        file_sha256=file_sha256,
        file_path=file_path,
        source_data=source_data,
    )
