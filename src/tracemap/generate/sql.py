"""Generate dbt CDM SQL from mapping_spec YAML.

For each spec file, writes one `dbt/models/cdm/<target_table>.sql`. The SQL is expressed
as a sequence of CTEs, one per field rule, then selected into the final table shape.
The file is regenerated on every build, so the mapping spec is the single source of truth.

The generator covers the straightforward rules. A few rules in the spec require logic
that is easier to express as hand-written intermediate models (observation_period from
derived min/max dates, location dedup, metadata row explosion, domain routing). For
target tables whose spec contains those, the generator emits a stub model with a
TODO banner so the file is never silently empty.
"""

from pathlib import Path

from tracemap.config import REPO_ROOT
from tracemap.spec.models import (
    CastDateRule,
    CastDateTimeRule,
    CastIntRule,
    CastNumericRule,
    ConstantRule,
    CopyRule,
    FieldRule,
    LookupRule,
    MappingSpec,
    SourceConceptLookupRule,
    SourceMapping,
    StandardConceptMapRule,
    UnitMapRule,
    ValueAsConceptMapRule,
    load_all_specs,
)

CDM_MODELS_DIR = REPO_ROOT / "dbt" / "models" / "cdm"

GENERATED_BANNER = (
    "-- GENERATED by tracemap generate from mapping_spec/{spec}.yml v{version}. "
    "Do not edit by hand."
)

# Rules whose SQL depends on a derived column computed in an intermediate model.
_DERIVED_PREFIXES = ("__derived_", "_derived_", "__derived")

# Rules the generator cannot yet express. Specs that contain any of these are skipped and
# a stub file is emitted so the model is never silently absent.
_UNSUPPORTED_RULES_FOR_TABLE: dict[str, str] = {
    "observation_period": "Needs derived min/max event dates across all event tables.",
    "location": "Needs address de-duplication and derived location_id.",
    "care_site": "Needs location_key_map built from the intermediate location table.",
    "metadata": "Needs row explosion over several metadata items at build time.",
    "cdm_source": "Needs derived release dates and vocabulary_version from cdm_run.",
    "measurement": "Needs filter on category IN ('laboratory', 'vital-signs').",
    "observation": "Needs filter on category NOT IN ('laboratory', 'vital-signs').",
    "condition_occurrence": "Phase 2: unions Synthea SNOMED and UK ICD-10 sources.",
    "person": "Phase 2: unions Synthea and UK patient tables.",
}


def staging_model(source_table: str) -> str:
    """raw.synthea_patients -> stg_synthea__patients (dbt ref)."""
    schema, _, table = source_table.partition(".")
    if schema != "raw" or not table.startswith("synthea_"):
        return source_table
    return f"stg_synthea__{table.removeprefix('synthea_')}"


def expr_for_rule(rule: FieldRule, source_alias: str) -> str:
    """Return a SQL expression producing the target column from the source alias."""
    if isinstance(rule, CopyRule):
        if rule.from_.lower().startswith(_DERIVED_PREFIXES):
            return f"null::text /* {rule.from_} filled by intermediate model */"
        return f"{source_alias}.{rule.from_.lower()}"
    if isinstance(rule, CastDateRule):
        return f"{source_alias}.{rule.from_.lower()}::date"
    if isinstance(rule, CastDateTimeRule):
        return f"{source_alias}.{rule.from_.lower()}::timestamp"
    if isinstance(rule, CastIntRule):
        if rule.target in {"year_of_birth", "month_of_birth", "day_of_birth"}:
            part = rule.target.split("_", 1)[0]
            return f"cast(extract({part} from {source_alias}.{rule.from_.lower()}::date) as int)"
        return f"{source_alias}.{rule.from_.lower()}::bigint"
    if isinstance(rule, CastNumericRule):
        return (
            f"case when {source_alias}.{rule.from_.lower()} ~ '^-?\\d+(\\.\\d+)?$' "
            f"then {source_alias}.{rule.from_.lower()}::numeric else null end"
        )
    if isinstance(rule, ConstantRule):
        if rule.value is None:
            return "null"
        if isinstance(rule.value, str):
            escaped = rule.value.replace("'", "''")
            return f"'{escaped}'"
        return str(rule.value)
    if isinstance(rule, LookupRule):
        alias = _lookup_alias(rule.via)
        column = _lookup_column(rule.via)
        return f"{alias}.{column}"
    if isinstance(rule, StandardConceptMapRule):
        alias = f"std_{rule.target}"
        return f"coalesce({alias}.standard_concept_id, 0)"
    if isinstance(rule, SourceConceptLookupRule):
        alias = f"src_{rule.target}"
        return f"coalesce({alias}.source_concept_id, 0)"
    if isinstance(rule, UnitMapRule):
        alias = f"unit_{rule.target}"
        return f"coalesce({alias}.concept_id, 0)"
    if isinstance(rule, ValueAsConceptMapRule):
        alias = f"val_{rule.target}"
        return f"coalesce({alias}.concept_id, 0)"
    raise TypeError(f"Unknown rule type: {type(rule).__name__}")


def _lookup_alias(via: str) -> str:
    """etl_meta.person_key_map -> km_person_key_map."""
    _, _, table = via.partition(".")
    return f"km_{table}"


def _lookup_column(via: str) -> str:
    """Derive the result column on the lookup table (convention: person_key_map ->
    person_id, visit_source_key_map -> visit_occurrence_id, etc.)."""
    _, _, table = via.partition(".")
    # Convention embedded in the intermediate model names.
    convention = {
        "person_key_map": "person_id",
        "visit_source_key_map": "visit_occurrence_id",
        "care_site_key_map": "care_site_id",
        "provider_key_map": "provider_id",
        "location_key_map": "location_id",
        "synthea_encounterclass_map": "visit_concept_id",
    }
    return convention.get(table, table.removesuffix("_map"))


def join_clauses(source_mapping: SourceMapping, source_alias: str) -> list[str]:
    """Build dbt ref() / source() joins needed by the rules in this source mapping."""
    clauses: list[str] = []
    seen: set[str] = set()
    for rule in source_mapping.fields:
        if isinstance(rule, LookupRule):
            alias = _lookup_alias(rule.via)
            if alias in seen:
                continue
            seen.add(alias)
            key_col = "source_patient_id" if "person" in rule.via else "source_id"
            via_table = rule.via.partition(".")[2]
            clauses.append(
                f"left join {{{{ ref('int_{via_table}') }}}} {alias} "
                f"on {alias}.{key_col} = {source_alias}.{rule.from_.lower()}"
            )
        elif isinstance(rule, StandardConceptMapRule):
            alias = f"std_{rule.target}"
            if alias in seen:
                continue
            seen.add(alias)
            clauses.append(
                f"left join {{{{ ref('int_standard_concept_map') }}}} {alias} "
                f"on {alias}.source_vocabulary_id = '{rule.source_vocabulary}' "
                f"and {alias}.source_code = {source_alias}.{rule.from_.lower()}"
            )
        elif isinstance(rule, SourceConceptLookupRule):
            alias = f"src_{rule.target}"
            if alias in seen:
                continue
            seen.add(alias)
            clauses.append(
                f"left join {{{{ ref('int_source_concept_lookup') }}}} {alias} "
                f"on {alias}.source_vocabulary_id = '{rule.source_vocabulary}' "
                f"and {alias}.source_code = {source_alias}.{rule.from_.lower()}"
            )
        elif isinstance(rule, UnitMapRule):
            alias = f"unit_{rule.target}"
            clauses.append(
                f"left join {{{{ ref('int_ucum_unit_map') }}}} {alias} "
                f"on {alias}.source_unit = {source_alias}.{rule.from_.lower()}"
            )
            seen.add(alias)
        elif isinstance(rule, ValueAsConceptMapRule):
            alias = f"val_{rule.target}"
            clauses.append(
                f"left join {{{{ ref('int_value_as_concept_map') }}}} {alias} "
                f"on {alias}.source_value = {source_alias}.{rule.from_.lower()}"
            )
            seen.add(alias)
    return clauses


def generate_cdm_model(spec: MappingSpec) -> str:
    """Produce the full dbt .sql file for one spec."""
    banner = GENERATED_BANNER.format(spec=spec.target_table, version=spec.spec_version)

    if spec.target_table in _UNSUPPORTED_RULES_FOR_TABLE:
        reason = _UNSUPPORTED_RULES_FOR_TABLE[spec.target_table]
        return (
            f"{banner}\n"
            f"-- STUB: {reason}\n"
            f"-- TODO: write a hand-crafted intermediate model and finalise this model.\n\n"
            f"{{{{ config(materialized='table', schema='cdm', "
            f"alias='{spec.target_table}') }}}}\n\n"
            f"select 1 as _placeholder where false\n"
        )

    if len(spec.sources) != 1:
        # Phase 1: one source per table. UK extract (Phase 2) will need a union.
        return (
            f"{banner}\n-- TODO: multi-source union not yet supported by generator.\n"
            f"select 1 as _placeholder where false\n"
        )

    source = spec.sources[0]
    source_alias = "src"
    staging = staging_model(source.source_table)
    staging_ref = f"{{{{ ref('{staging}') }}}}"

    select_lines = [
        f"    {expr_for_rule(rule, source_alias)} as {rule.target}," for rule in source.fields
    ]
    if select_lines:
        select_lines[-1] = select_lines[-1].rstrip(",")

    joins = "\n".join(join_clauses(source, source_alias))

    sql = [
        banner,
        f"-- Target: cdm.{spec.target_table}",
        f"-- Source: {source.source_table} (grain: {source.grain})",
        "",
        f"{{{{ config(materialized='table', schema='cdm', alias='{spec.target_table}') }}}}",
        "",
        "select",
        *select_lines,
        f"from {staging_ref} {source_alias}",
    ]
    if joins:
        sql.append(joins)
    if source.where:
        sql.append(f"where {source.where}")
    return "\n".join(sql) + "\n"


def write_cdm_models(spec_dir: Path | None = None, out_dir: Path | None = None) -> list[Path]:
    """Write every CDM model file. Returns the paths written.

    Tables in _UNSUPPORTED_RULES_FOR_TABLE are left alone: their file on disk is the
    hand-written override that finalises the stub, and overwriting it would clobber the
    override. The generator only ever touches files for tables it fully generates.
    """
    out_dir = out_dir or CDM_MODELS_DIR
    out_dir.mkdir(parents=True, exist_ok=True)
    written = []
    for name, spec in sorted(load_all_specs(spec_dir).items()):
        if name in _UNSUPPORTED_RULES_FOR_TABLE:
            continue
        path = out_dir / f"{name}.sql"
        path.write_text(generate_cdm_model(spec), encoding="utf-8")
        written.append(path)
    return written
