"""Generate dbt schema tests (not_null, relationships) from mapping_spec YAML.

Writes one `dbt/models/cdm/schema.yml` describing every generated model. Non-null tests
are added for the columns the OMOP CDM v5.4 DDL marks NOT NULL (looked up from the
loaded DDL in ddl/). This way the dbt tests enforce the same constraints Postgres does,
so a planned test failure is surfaced in dbt output rather than as a runtime error.
"""

import re
from pathlib import Path

import yaml

from tracemap.config import REPO_ROOT
from tracemap.load import ddl
from tracemap.spec.models import MappingSpec, load_all_specs

CDM_MODELS_DIR = REPO_ROOT / "dbt" / "models" / "cdm"
SCHEMA_YML_PATH = CDM_MODELS_DIR / "schema.yml"


def _parse_not_null_columns(table: str) -> set[str]:
    """Return the NOT NULL columns of one cdm table from the OHDSI DDL."""
    text = ddl.DDL_FILE.read_text(encoding="utf-8")
    match = re.search(
        rf"CREATE TABLE @cdmDatabaseSchema\.{table}\s*\((.*?)\);",
        text,
        re.IGNORECASE | re.DOTALL,
    )
    if not match:
        return set()
    body = match.group(1)
    not_null = set()
    for line in body.splitlines():
        line = line.strip().rstrip(",")
        if not line:
            continue
        m = re.match(r"(\w+)\s+\S+.*NOT NULL", line, re.IGNORECASE)
        if m:
            not_null.add(m.group(1).lower())
    return not_null


def _column_tests(table: str, target: str, not_null: set[str]) -> list[str]:
    tests = []
    if target in not_null:
        tests.append("not_null")
    # Primary key columns end in _id and are the table's surrogate key.
    if target == f"{table}_id":
        tests.append("unique")
    return tests


def build_schema_entry(spec: MappingSpec) -> dict:
    not_null = _parse_not_null_columns(spec.target_table)
    columns = []
    for source in spec.sources:
        for rule in source.fields:
            tests = _column_tests(spec.target_table, rule.target, not_null)
            entry: dict = {"name": rule.target}
            if rule.notes:
                entry["description"] = rule.notes
            if tests:
                entry["tests"] = tests
            columns.append(entry)
    return {
        "name": spec.target_table,
        "description": (
            (spec.description or "").strip()
            or (
                f"OMOP CDM v5.4 {spec.target_table}. "
                f"Generated from mapping_spec/{spec.target_table}.yml."
            )
        ),
        "columns": columns,
    }


def write_schema_tests(spec_dir: Path | None = None, out_path: Path | None = None) -> Path:
    out_path = out_path or SCHEMA_YML_PATH
    models = [build_schema_entry(spec) for _, spec in sorted(load_all_specs(spec_dir).items())]
    data = {"version": 2, "models": models}
    out_path.parent.mkdir(parents=True, exist_ok=True)
    out_path.write_text(
        "# GENERATED by tracemap generate. Do not edit by hand.\n"
        + yaml.safe_dump(data, sort_keys=False, width=100),
        encoding="utf-8",
    )
    return out_path
